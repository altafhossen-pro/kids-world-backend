const colors = [
    { name: 'Red', hex: '#FF0000' },
    { name: 'Blue', hex: '#0000FF' },
    { name: 'Black', hex: '#000000' },
    { name: 'Pink', hex: '#FFC0CB' },
    { name: 'White', hex: '#FFFFFF' },
    { name: 'Yellow', hex: '#FFFF00' }
];

const sizes = ['Standard', 'Large', 'Small'];

const generateSlug = (text) => {
    return text.toLowerCase().replace(/[^a-z0-9 -]/g, '').replace(/\s+/g, '-').replace(/-+/g, '-') + '-' + Math.floor(Math.random() * 1000);
};

const seedProducts = async () => {
    try {
        await mongoose.connect(MONGODB_URI);
        console.log('Connected to MongoDB');

        console.log('Clearing existing products and categories...');
        await Product.deleteMany({}); 
        // We shouldn't delete categories if the user has custom ones, but we will find or create them
        
        let count = 0;
        const productsToInsert = [];
        const categoryMap = {};

        for (let i = 0; i < productsData.length; i++) {
            const item = productsData[i];
            const name = item.name;
            const catName = item.cat;

            // Find or create category
            if (!categoryMap[catName]) {
                let cat = await Category.findOne({ name: catName });
                if (!cat) {
                    cat = await Category.create({
                        name: catName,
                        slug: generateSlug(catName),
                        description: `Category for ${catName}`
                    });
                }
                categoryMap[catName] = cat._id;
            }

            const basePrice = Math.floor(Math.random() * 15000) + 1000;
            
            // Pick 1-3 colors
            const numColors = Math.floor(Math.random() * 2) + 1;
            const selectedColors = [];
            for (let i = 0; i < numColors; i++) {
                const c = colors[Math.floor(Math.random() * colors.length)];
                if (!selectedColors.find(sc => sc.name === c.name)) selectedColors.push(c);
            }

            // Pick 1-3 sizes
            const numSizes = Math.floor(Math.random() * 2) + 2; // 2 to 3 sizes
            const selectedSizes = [];
            for (let i = 0; i < numSizes; i++) {
                const s = sizes[Math.floor(Math.random() * sizes.length)];
                if (!selectedSizes.includes(s)) selectedSizes.push(s);
            }

            const variants = [];
            let vIndex = 0;
            const finalAvailableColors = new Set();
            const finalAvailableSizes = new Set();

            for (const color of selectedColors) {
                for (const size of selectedSizes) {
                    // Randomly skip about 30% of the combinations to create uneven variants
                    // Ensure at least one variant is always added by not skipping if it's the very first combination
                    if (vIndex > 0 && Math.random() < 0.3) {
                        continue;
                    }

                    variants.push({
                        sku: `KW-${Math.floor(Math.random() * 1000000)}-${vIndex++}`,
                        currentPrice: basePrice + (Math.floor(Math.random() * 1000) - 500),
                        stockQuantity: Math.floor(Math.random() * 50) + 5,
                        stockStatus: 'in_stock',
                        attributes: [
                            { name: 'Color', value: color.name, hexCode: color.hex },
                            { name: 'Size', value: size }
                        ]
                    });
                    
                    finalAvailableColors.add(color.name);
                    finalAvailableSizes.add(size);
                }
            }
            const availableColors = Array.from(finalAvailableColors);
            const availableSizes = Array.from(finalAvailableSizes);

            const productImages = [];
            const mainImageUrl = imageUrls[Math.floor(Math.random() * imageUrls.length)];
            productImages.push({ url: mainImageUrl, isPrimary: true });
            productImages.push({ url: imageUrls[Math.floor(Math.random() * imageUrls.length)], isPrimary: false });

            productsToInsert.push({
                title: name,
                slug: generateSlug(name),
                category: categoryMap[catName],
                status: 'published',
                isActive: true,
                productType: 'variable',
                basePrice: basePrice,
                featuredImage: mainImageUrl, // FIXED: Set featuredImage for the admin view
                shortDescription: `High quality ${name} perfect for kids.`,
                description: `This is the ultimate ${name}, bringing joy and fun to your kids' playtime.`,
                gallery: productImages,
                variants: variants,
                availableAttributes: [
                    { name: 'Color', values: availableColors },
                    { name: 'Size', values: sizes }
                ]
            });
            count++;
        }

        await Product.insertMany(productsToInsert);
        console.log(`Successfully inserted ${count} products with categories and featured images!`);

    } catch (error) {
        console.error('Error seeding products:', error);
    } finally {
        await mongoose.disconnect();
        console.log('Disconnected from MongoDB');
    }
};

seedProducts();
