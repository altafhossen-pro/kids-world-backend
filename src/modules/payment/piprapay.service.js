const axios = require('axios');
const Settings = require('../settings/settings.model');
const { Order } = require('../order/order.model');
const socketConfig = require('../../socket');

class PiprapayService {
  /**
   * Get active PipraPay configuration
   */
  async getConfig() {
    const settings = await Settings.findOne();
    const piprapay = settings?.piprapaySettings || {};

    const apiKey = piprapay.apiKey || process.env.PIPRAPAY_API_KEY || '';
    let baseUrl = piprapay.baseUrl || process.env.PIPRAPAY_BASE_URL || 'https://piprapay.com/api';
    baseUrl = baseUrl.trim().replace(/\/+$/, '');

    // Ensure URL has /api suffix if missing
    if (!baseUrl.endsWith('/api') && !baseUrl.includes('/api/')) {
      baseUrl = `${baseUrl}/api`;
    }

    return {
      isEnabled: Boolean(piprapay.isEnabled),
      showOnCheckout: Boolean(piprapay.showOnCheckout),
      displayName: piprapay.displayName || 'Online Payment (bKash / Nagad / Rocket / Cards)',
      apiKey: apiKey.trim(),
      baseUrl,
    };
  }

  /**
   * Create a checkout charge via PipraPay
   * @param {Object} order - Order document or plain object
   */
  async createCharge(order) {
    const config = await this.getConfig();

    if (!config.isEnabled) {
      return {
        success: false,
        message: 'PipraPay payment gateway is currently disabled in settings.',
      };
    }

    if (!config.apiKey) {
      return {
        success: false,
        message: 'PipraPay API key is not configured in settings.',
      };
    }

    const backendUrl = (process.env.BACKEND_URL || 'http://localhost:5000').trim().replace(/\/+$/, '');
    const callbackUrl = `${backendUrl}/api/v1/payment/piprapay/callback?order_id=${order._id}&order_number=${order.orderId}`;
    const webhookUrl = `${backendUrl}/api/v1/payment/piprapay/webhook?order_id=${order._id}&order_number=${order.orderId}`;

    // Extract customer details
    const customerName = order.shippingAddress?.name || order.guestInfo?.name || 'Valued Customer';
    const customerPhone = order.shippingAddress?.phone || order.guestInfo?.phone || '01700000000';
    const customerEmail = order.guestInfo?.email || `${customerPhone}@kidsworld.com.bd`;

    const metadata = {
      orderId: order._id?.toString(),
      orderNumber: order.orderId,
      amount: String(order.total),
      isGuestOrder: order.isGuestOrder,
    };

    const payload = {
      full_name: customerName,
      email_address: customerEmail,
      mobile_number: customerPhone,
      amount: String(order.total),
      currency: 'BDT',
      metadata: JSON.stringify(metadata),
      return_url: callbackUrl,
      webhook_url: webhookUrl,
    };

    try {
      const endpoint = `${config.baseUrl}/checkout/redirect`;
      const response = await axios.post(endpoint, payload, {
        headers: {
          'MHS-PIPRAPAY-API-KEY': config.apiKey,
          Accept: 'application/json',
          'Content-Type': 'application/json',
        },
        timeout: 30000,
      });

      const data = response.data || {};
      const ppUrl = data.pp_url || data.payment_url || data.url || data.data?.pp_url || data.data?.payment_url;

      if (ppUrl) {
        return {
          success: true,
          pp_url: ppUrl,
          invoice: data.invoice || data.data?.invoice || null,
          data,
        };
      }

      console.error('PipraPay initiation response missing pp_url:', data);
      return {
        success: false,
        message: data.message || 'Payment URL could not be generated by PipraPay.',
      };
    } catch (error) {
      const errDetails = error.response?.data || error.message;
      console.error('PipraPay Charge Initiation Error:', errDetails);

      const errorMessage =
        error.response?.data?.error?.message ||
        error.response?.data?.message ||
        (typeof error.response?.data?.error === 'string' ? error.response.data.error : null) ||
        error.message ||
        'Failed to connect to PipraPay.';

      // Safely log error without affecting checkout response
      try {
        const { logPiprapayError } = require('./piprapay.logger');
        logPiprapayError('Create Charge', errDetails, {
          orderId: order._id?.toString(),
          orderNumber: order.orderId,
          amount: order.total,
          endpoint,
        });
      } catch (logErr) {
        // Silent fail for logger
      }

      return {
        success: false,
        message: errorMessage,
      };
    }
  }

  /**
   * Verify payment status directly with PipraPay server
   * @param {string} ppId - Transaction reference / pp_id from PipraPay
   */
  async verifyPayment(ppId) {
    if (!ppId) {
      return { success: false, verified: false, message: 'Transaction reference is missing' };
    }

    const config = await this.getConfig();
    if (!config.apiKey) {
      return { success: false, verified: false, message: 'PipraPay API key is not configured' };
    }

    try {
      const endpoint = `${config.baseUrl}/verify-payment`;
      const response = await axios.post(
        endpoint,
        { pp_id: ppId },
        {
          headers: {
            'MHS-PIPRAPAY-API-KEY': config.apiKey,
            Accept: 'application/json',
            'Content-Type': 'application/json',
          },
          timeout: 25000,
        }
      );

      const resData = response.data || {};
      const status = String(resData.status || '').toLowerCase();
      const isPaid = ['success', 'completed', 'paid'].includes(status);

      return {
        success: true,
        verified: isPaid,
        data: resData,
      };
    } catch (error) {
      const errDetails = error.response?.data || error.message;
      console.error('PipraPay Payment Verification Error:', errDetails);
      return {
        success: false,
        verified: false,
        message: error.response?.data?.message || error.message,
      };
    }
  }

  /**
   * Process successful payment and mark order as paid
   * @param {string} orderId - MongoDB _id or 6-digit orderId
   * @param {Object} paymentData - Verification response data
   */
  async processSuccess(orderId, paymentData = {}) {
    const query = orderId.toString().length === 24 
      ? { _id: orderId } 
      : { $or: [{ _id: orderId }, { orderId: orderId }] };

    const order = await Order.findOne(query);
    if (!order) {
      console.error(`PipraPay processSuccess: Order ${orderId} not found`);
      return null;
    }

    const ppId = paymentData.pp_id || paymentData.transaction_ref;

    // Idempotency check: Guard against duplicate processing
    if (order.paymentStatus === 'paid' && order.piprapayDetails?.ppId === ppId) {
      return order;
    }

    order.paymentStatus = 'paid';
    order.paymentMethod = 'piprapay';
    order.piprapayDetails = {
      ppId: ppId || order.piprapayDetails?.ppId,
      amount: Number(paymentData.amount) || order.total,
      currency: paymentData.currency || 'BDT',
      paymentMethod: paymentData.payment_method || 'piprapay',
      paidAt: new Date(),
      rawResponse: paymentData,
    };

    if (!order.tracking) {
      order.tracking = [];
    }
    order.tracking.push({
      status: 'paid',
      date: new Date(),
      note: `Payment of ৳${paymentData.amount || order.total} verified via PipraPay (${paymentData.payment_method || 'Online'}) [Trx: ${ppId || 'N/A'}]`,
    });

    await order.save();

    // Trigger Telegram notification for successful online payment
    try {
      const { sendTelegramNotification } = require('../../utils/telegram');
      const isGuest = Boolean(order.isGuestOrder || !order.user);

      let customerName = order.shippingAddress?.name || order.guestInfo?.name || order.manualOrderInfo?.name;
      let customerPhone = order.shippingAddress?.phone || order.guestInfo?.phone || order.manualOrderInfo?.phone;
      let customerEmail = order.guestInfo?.email || order.shippingAddress?.email || order.manualOrderInfo?.email;

      if (!customerName && order.user) {
        try {
          const { User } = require('../user/user.model');
          const u = await User.findById(order.user).select('name phone email').lean();
          if (u) {
            customerName = customerName || u.name;
            customerPhone = customerPhone || u.phone;
            customerEmail = customerEmail || u.email;
          }
        } catch (uErr) {
          // Ignore
        }
      }

      const telegramPayload = {
        orderId: order.orderId,
        orderNumber: order.orderId,
        isGuest,
        customerName: customerName || (isGuest ? 'Guest Customer' : 'Registered Customer'),
        phone: customerPhone || 'N/A',
        email: customerEmail || '',
        amount: Number(paymentData.amount) || order.total,
        orderTotal: order.total,
        currency: paymentData.currency || 'BDT',
        paymentMethod: paymentData.payment_method || 'PipraPay Online',
        ppId: ppId || 'N/A',
        transactionId: ppId || 'N/A',
        paidAt: new Date().toLocaleString('en-US', { timeZone: 'Asia/Dhaka' }),
        items: order.items ? order.items.map(item => ({
          productTitle: item.name || 'Product',
          quantity: item.quantity,
          price: item.price,
        })) : [],
      };

      sendTelegramNotification('PIPRAPAY_PAYMENT_SUCCESS', telegramPayload).catch(err => {
        console.error('Failed to send Telegram notification for PipraPay success:', err.message);
      });
    } catch (telegramErr) {
      console.error('Telegram notification trigger error:', telegramErr.message);
    }

    // Emit live update to admin panel
    try {
      if (socketConfig && typeof socketConfig.getIo === 'function') {
        const io = socketConfig.getIo();
        if (io) {
          io.emit('order-payment-updated', {
            orderId: order.orderId,
            _id: order._id,
            paymentStatus: 'paid',
            paymentMethod: 'piprapay',
            total: order.total,
          });
        }
      }
    } catch (e) {
      // Socket not initialized or non-critical error
    }

    return order;
  }
}

module.exports = new PiprapayService();
